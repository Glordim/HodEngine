#include "HodEngine/RHI/D3d12/D3d12Shader.hpp"

#include "HodEngine/RHI/ShaderConstantDescriptor.hpp"

#include <HodEngine/Core/Document/Document.hpp>
#include <HodEngine/Core/Document/DocumentReaderJson.hpp>
#include <HodEngine/Core/Output/OutputService.hpp>

#include <cstring>

namespace hod::inline rhi
{
	/// @brief
	/// @param type
	D3d12Shader::D3d12Shader(ShaderType type)
	: Shader(type)
	{
	}

	/// @brief
	/// @param bytecode
	/// @param bytecodeSize
	/// @param reflection
	/// @param reflectionSize
	/// @return
	bool D3d12Shader::LoadFromIR(const void* bytecode, uint32_t bytecodeSize, const char* reflection, uint32_t reflectionSize)
	{
		_buffer.Resize(bytecodeSize);
		std::memcpy(_buffer.Data(), bytecode, bytecodeSize);

		if (GenerateDescriptors(reflection, reflectionSize) == false)
		{
			OUTPUT_ERROR("D3d12Shader: Failed to extract descriptor");
			return false;
		}

		// What the common descriptors don't keep: where the push constant is, and the semantics of the vertex inputs
		Document           reflectionDocument;
		DocumentReaderJson documentReader;
		if (documentReader.Read(reflectionDocument, reflection, reflectionSize) == false)
		{
			return false;
		}

		ExtractPushConstantRegister(reflectionDocument.GetRootNode());

		if (GetShaderType() == ShaderType::Vertex)
		{
			const DocumentNode* entryPointsNode = reflectionDocument.GetRootNode().GetChild("entryPoints");
			const DocumentNode* entryPointNode = entryPointsNode != nullptr ? entryPointsNode->GetFirstChild() : nullptr;
			const DocumentNode* parametersNode = entryPointNode != nullptr ? entryPointNode->GetChild("parameters") : nullptr;
			if (parametersNode != nullptr)
			{
				for (const DocumentNode* parameterNode = parametersNode->GetFirstChild(); parameterNode != nullptr; parameterNode = parameterNode->GetNextSibling())
				{
					ExtractVertexInputSemantics(*parameterNode);
				}
			}
		}

		return true;
	}

	/// @brief The push constant is the one constant buffer the common code left out of the sets (see Shader::GenerateDescriptors)
	/// @param reflectionNode
	void D3d12Shader::ExtractPushConstantRegister(const DocumentNode& reflectionNode)
	{
		_hasPushConstant = false;

		const DocumentNode* parametersNode = reflectionNode.GetChild("parameters");
		if (GetConstantDescriptor() == nullptr || parametersNode == nullptr)
		{
			return;
		}

		for (const DocumentNode* parameterNode = parametersNode->GetFirstChild(); parameterNode != nullptr; parameterNode = parameterNode->GetNextSibling())
		{
			const DocumentNode* userAttribsNode = parameterNode->GetChild("userAttribs");
			const DocumentNode* bindingNode = parameterNode->GetChild("binding");
			const DocumentNode* indexNode = bindingNode != nullptr ? bindingNode->GetChild("index") : nullptr;
			if (userAttribsNode == nullptr || indexNode == nullptr)
			{
				continue;
			}

			for (const DocumentNode* attributeNode = userAttribsNode->GetFirstChild(); attributeNode != nullptr; attributeNode = attributeNode->GetNextSibling())
			{
				const DocumentNode* nameNode = attributeNode->GetChild("name");
				if (nameNode == nullptr || nameNode->GetString() != "PushConstant")
				{
					continue;
				}

				const DocumentNode* spaceNode = bindingNode->GetChild("space");

				_pushConstantRegister._index = indexNode->GetUInt32();
				_pushConstantRegister._space = spaceNode != nullptr ? spaceNode->GetUInt32() : 0;
				_hasPushConstant = true;
				return;
			}
		}
	}

	/// @brief
	/// @param variableNode a parameter of the entry point, or a field of one
	void D3d12Shader::ExtractVertexInputSemantics(const DocumentNode& variableNode)
	{
		const DocumentNode* semanticNameNode = variableNode.GetChild("semanticName");
		if (semanticNameNode != nullptr)
		{
			const String& semanticName = semanticNameNode->GetString();
			if (semanticName.StartsWith("SV_"))
			{
				return; // generated by the system, not read from a vertex buffer
			}

			VertexInputSemantic semantic;
			semantic._name = semanticName;

			const DocumentNode* semanticIndexNode = variableNode.GetChild("semanticIndex");
			if (semanticIndexNode != nullptr)
			{
				semantic._index = semanticIndexNode->GetUInt32();
			}

			_vertexInputSemantics.PushBack(std::move(semantic));
			return;
		}

		const DocumentNode* typeNode = variableNode.GetChild("type");
		const DocumentNode* fieldsNode = typeNode != nullptr ? typeNode->GetChild("fields") : nullptr;
		if (fieldsNode != nullptr)
		{
			for (const DocumentNode* fieldNode = fieldsNode->GetFirstChild(); fieldNode != nullptr; fieldNode = fieldNode->GetNextSibling())
			{
				ExtractVertexInputSemantics(*fieldNode);
			}
		}
	}

	/// @brief
	/// @return
	D3D12_SHADER_BYTECODE D3d12Shader::GetBytecode() const
	{
		D3D12_SHADER_BYTECODE bytecode;
		bytecode.pShaderBytecode = _buffer.Data();
		bytecode.BytecodeLength = _buffer.Size();
		return bytecode;
	}

	/// @brief
	/// @return
	const D3d12Shader::Register* D3d12Shader::GetPushConstantRegister() const
	{
		return _hasPushConstant ? &_pushConstantRegister : nullptr;
	}

	/// @brief
	/// @return
	const Vector<D3d12Shader::VertexInputSemantic>& D3d12Shader::GetVertexInputSemantics() const
	{
		return _vertexInputSemantics;
	}
}
